import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { spawnSync } from "node:child_process";
import { after, describe, it } from "node:test";
import { fileURLToPath } from "node:url";
import { mergeVersionSection, unreleasedBody } from "./render-changelog.mjs";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));

const CARGO_TOML = `[workspace]
resolver = "2"
members = [
    "crates/alpha",
    "crates/beta",
]

[workspace.package]
version = "0.1.0"
edition = "2021"
`;

const CARGO_LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "alpha"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.228"

[[package]]
name = "beta"
version = "0.1.0"
`;

const CHANGELOG = `# Changelog

## [Unreleased]

## [0.1.1] - 2026-01-02

### Fixed

- Something.

## [0.1.0] - 2026-01-01

### Added

- Initial.
`;

/** @type {string[]} */
const tempDirs = [];

/**
 * @returns {string} Fixture workspace root; the scripts read it via MINDCORE_REPO_ROOT.
 */
function createFixture() {
  const root = mkdtempSync(join(tmpdir(), "mindcore-release-"));
  tempDirs.push(root);
  mkdirSync(join(root, "crates/alpha"), { recursive: true });
  mkdirSync(join(root, "crates/beta"), { recursive: true });
  writeFileSync(join(root, "Cargo.toml"), CARGO_TOML);
  writeFileSync(join(root, "Cargo.lock"), CARGO_LOCK);
  writeFileSync(join(root, "CHANGELOG.md"), CHANGELOG);
  for (const member of ["alpha", "beta"]) {
    writeFileSync(
      join(root, "crates", member, "Cargo.toml"),
      `[package]\nname = "${member}"\nversion.workspace = true\npublish = false\n`,
    );
  }
  return root;
}

/**
 * @param {string} root
 * @param {string} script
 * @param {string[]} args
 */
function run(root, script, args) {
  return spawnSync(process.execPath, [join(SCRIPT_DIR, script), ...args], {
    cwd: root,
    env: { ...process.env, MINDCORE_REPO_ROOT: root },
    encoding: "utf8",
  });
}

after(() => {
  for (const dir of tempDirs) {
    rmSync(dir, { recursive: true, force: true });
  }
});

describe("next-version", () => {
  it("prints the current workspace version", () => {
    const result = run(createFixture(), "next-version.mjs", ["--current"]);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout.trim(), "0.1.0");
  });

  it("prints the patch bump with no argument", () => {
    const result = run(createFixture(), "next-version.mjs", []);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout.trim(), "0.1.1");
  });

  it("promotes a prerelease to its core version by default", () => {
    const root = createFixture();
    writeFileSync(
      join(root, "Cargo.toml"),
      CARGO_TOML.replace('version = "0.1.0"', 'version = "0.2.0-rc.1"'),
    );
    const result = run(root, "next-version.mjs", []);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout.trim(), "0.2.0");
  });

  it("takes the next patch from a stable version", () => {
    const root = createFixture();
    writeFileSync(
      join(root, "Cargo.toml"),
      CARGO_TOML.replace('version = "0.1.0"', 'version = "0.2.0"'),
    );
    const result = run(root, "next-version.mjs", []);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout.trim(), "0.2.1");
  });

  it("accepts a strictly greater version", () => {
    const result = run(createFixture(), "next-version.mjs", ["0.2.0-rc.1"]);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout.trim(), "0.2.0-rc.1");
  });

  it("refuses an equal, lower or malformed version", () => {
    const root = createFixture();
    for (const bad of ["0.1.0", "0.0.9", "not-a-version"]) {
      const result = run(root, "next-version.mjs", [bad]);
      assert.notEqual(result.status, 0, `${bad} should be refused`);
      assert.equal(result.stdout, "");
    }
  });

  it("rejects non-strict SemVer inputs", () => {
    const root = createFixture();
    for (const bad of ["0.02.0", "0.2.0-rc.01", "0.2.0-01", "0.2.0-", "0.2.0-alpha..1", "00.2.0"]) {
      const result = run(root, "next-version.mjs", [bad]);
      assert.notEqual(result.status, 0, `${bad} should be refused`);
      assert.match(result.stderr, /Invalid SemVer/);
    }
  });

  it("accepts a leading zero in an alphanumeric prerelease identifier", () => {
    const result = run(createFixture(), "next-version.mjs", ["0.2.0-01alpha"]);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout.trim(), "0.2.0-01alpha");
  });

  it("compares and bumps past 2^53 exactly", () => {
    const root = createFixture();
    writeFileSync(
      join(root, "Cargo.toml"),
      CARGO_TOML.replace('version = "0.1.0"', 'version = "1.0.9007199254740993"'),
    );

    const bumped = run(root, "next-version.mjs", []);
    assert.equal(bumped.status, 0, bumped.stderr);
    assert.equal(bumped.stdout.trim(), "1.0.9007199254740994");

    const above = run(root, "next-version.mjs", ["1.0.9007199254740994"]);
    assert.equal(above.status, 0, above.stderr);

    const below = run(root, "next-version.mjs", ["1.0.9007199254740992"]);
    assert.notEqual(below.status, 0);
  });
});

describe("bump-version", () => {
  it("rewrites the workspace version and every member lock entry only", () => {
    const root = createFixture();
    const result = run(root, "bump-version.mjs", ["0.1.1"]);
    assert.equal(result.status, 0, result.stderr);

    const cargo = readFileSync(join(root, "Cargo.toml"), "utf8");
    assert.match(cargo, /^\[workspace\.package\]\nversion = "0\.1\.1"$/m);

    const lock = readFileSync(join(root, "Cargo.lock"), "utf8");
    assert.match(lock, /name = "alpha"\nversion = "0\.1\.1"/);
    assert.match(lock, /name = "beta"\nversion = "0\.1\.1"/);
    assert.match(lock, /name = "serde"\nversion = "1\.0\.228"/);
    assert.equal(lock.match(/version = "0\.1\.1"/g).length, 2);
    assert.equal(lock.match(/version = "0\.1\.0"/g), null);
  });

  it("refuses a version that is not strictly greater", () => {
    const root = createFixture();
    const result = run(root, "bump-version.mjs", ["0.1.0"]);
    assert.notEqual(result.status, 0);
    assert.equal(readFileSync(join(root, "Cargo.toml"), "utf8"), CARGO_TOML);
  });

  it("aborts when a workspace member is missing from the lock", () => {
    const root = createFixture();
    writeFileSync(join(root, "Cargo.lock"), CARGO_LOCK.replace(/\[\[package\]\]\nname = "beta"[\s\S]*$/, ""));
    const result = run(root, "bump-version.mjs", ["0.1.1"]);
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /beta/);
    assert.equal(readFileSync(join(root, "Cargo.toml"), "utf8"), CARGO_TOML);
  });
});

describe("extract-changelog-notes", () => {
  it("prints exactly the requested section", () => {
    const result = run(createFixture(), "extract-changelog-notes.mjs", ["0.1.1"]);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout, "### Fixed\n\n- Something.\n");
  });

  it("accepts a v-prefixed version and fails on a missing one", () => {
    const root = createFixture();
    const prefixed = run(root, "extract-changelog-notes.mjs", ["v0.1.0"]);
    assert.equal(prefixed.status, 0, prefixed.stderr);
    assert.equal(prefixed.stdout, "### Added\n\n- Initial.\n");

    const missing = run(root, "extract-changelog-notes.mjs", ["9.9.9"]);
    assert.equal(missing.status, 1);
    assert.equal(missing.stdout, "");
    assert.match(missing.stderr, /no "## \[9\.9\.9\]" section/);
    assert.match(missing.stderr, /headings found: Unreleased, 0\.1\.1, 0\.1\.0/);
  });

  it("reports an invalid version distinctly", () => {
    const result = run(createFixture(), "extract-changelog-notes.mjs", ["0.02.0"]);
    assert.equal(result.status, 1);
    assert.equal(result.stdout, "");
    assert.match(result.stderr, /invalid SemVer "0\.02\.0"/);
  });

  it("reports an empty section distinctly", () => {
    const root = createFixture();
    writeFileSync(
      join(root, "CHANGELOG.md"),
      "# Changelog\n\n## [0.2.0] - 2026-01-03\n\n## [0.1.0] - 2026-01-01\n\n- Initial.\n",
    );
    const result = run(root, "extract-changelog-notes.mjs", ["0.2.0"]);
    assert.equal(result.status, 1);
    assert.equal(result.stdout, "");
    assert.match(result.stderr, /"## \[0\.2\.0\]" section is empty/);
  });

  it("reads the changelog given as the second argument", () => {
    const root = createFixture();
    const file = join(root, "nightly.md");
    writeFileSync(file, "# Changelog\n\n## [0.3.0] - 2026-01-05\n\n### Added\n\n- From a file.\n");

    const relative = run(root, "extract-changelog-notes.mjs", ["0.3.0", "nightly.md"]);
    assert.equal(relative.status, 0, relative.stderr);
    assert.equal(relative.stdout, "### Added\n\n- From a file.\n");

    const absolute = run(root, "extract-changelog-notes.mjs", ["0.3.0", file]);
    assert.equal(absolute.status, 0, absolute.stderr);
    assert.equal(absolute.stdout, "### Added\n\n- From a file.\n");

    const missing = run(root, "extract-changelog-notes.mjs", ["0.3.0", "absent.md"]);
    assert.equal(missing.status, 1);
    assert.equal(missing.stdout, "");
    assert.match(missing.stderr, /cannot read absent\.md/);
  });
});

describe("render-changelog", () => {
  it("keeps a present version section and injects the curated body under it", () => {
    const generated = "# Changelog\n\n## [0.2.0] - 2026-01-03\n\n### Added\n\n- Thing.\n";
    const merged = mergeVersionSection(generated, "0.2.0", {
      body: "Migration: rename `a` to `b`.",
      date: "2026-01-04",
    });
    assert.ok(
      merged.startsWith(
        "# Changelog\n\n## [0.2.0] - 2026-01-03\n\nMigration: rename `a` to `b`.\n\n### Added\n",
      ),
      merged,
    );
  });

  it("leaves a section untouched without a curated body", () => {
    const generated = "# Changelog\n\n## [0.2.0] - 2026-01-03\n\n### Added\n\n- Thing.\n";
    assert.equal(
      mergeVersionSection(generated, "0.2.0", { body: null, date: "2026-01-04" }),
      generated,
    );
  });

  it("inserts a placeholder section when git-cliff produced none", () => {
    const generated = "# Changelog\n\n## [0.1.0] - 2026-01-01\n\n- Initial.\n";
    const merged = mergeVersionSection(generated, "0.2.0", {
      body: null,
      date: "2026-01-04",
    });
    assert.equal(
      merged,
      "# Changelog\n\n## [0.2.0] - 2026-01-04\n\n_No user-visible changes._\n\n## [0.1.0] - 2026-01-01\n\n- Initial.\n",
    );
  });

  it("captures the Unreleased body only when it has content", () => {
    assert.equal(unreleasedBody("# Changelog\n\n## [Unreleased]\n\n## [0.1.0]\n\n- x\n"), null);
    assert.equal(
      unreleasedBody("# Changelog\n\n## [Unreleased]\n\nMigration notes.\n"),
      "Migration notes.",
    );
    assert.equal(unreleasedBody("# Changelog\n\n## [0.1.0]\n"), null);
  });
});
